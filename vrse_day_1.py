def isAnagram(s,t):
    if(len(s) != len(t)):
        return False
    freq = [0]*26
    for i in range(len(s)):
        sIdx = ord(s[i])-ord('a')
        freq[sIdx]+=1

        tIdx = ord(t[i])-ord('a')
        freq[tIdx]-=1

    for i in range(26):
        if(freq[i] != 0):
            return False
    return True

