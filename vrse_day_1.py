def findSingles(arr):
    freq = dict()
    for i in arr:
        if(freq.get(i) == None):
            freq[i] = 1
        else:
            freq[i] += 1
    res = []
    for i in freq.keys():
        if(freq[i] == 1):
            res.append(i)
    return res
res = findSingles([1,1,2,5,4,7,8,2,1,4,5,6,3,7])
